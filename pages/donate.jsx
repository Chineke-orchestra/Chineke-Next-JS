export async function getServerSideProps(context) {
  try {
    const data = await fetchPageData(context, 'donate');
    if (data.redirect) {
      return data;
    }
    return {
      props: data,
    };
  } catch (error) {
    console.error(`There was an error while fetching data: `, error);
    return {
      notFound: true,
    };
  }
}
