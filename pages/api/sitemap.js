import { setCacheHeaders } from 'utils/setCacheHeaders';
import fetch from 'node-fetch';

export default async function handler(req, res) {
  const { BACKEND_URL } = process.env;

  try {
    if (req.query.stylesheet) {
      const stylesheetUrl = `${BACKEND_URL}/modules/contrib/simple_sitemap/xsl/simple_sitemap.xsl`;
      const stylesheetResponse = await fetch(stylesheetUrl);

      if (!stylesheetResponse.ok) {
        const stylesheetError = await stylesheetResponse.text();
        console.error(`style fetch fail: ${stylesheetResponse.status}, response: ${stylesheetError}`);
        throw new Error(`style fetch fail: ${stylesheetResponse.status}`);
      }

      let stylesheetData = await stylesheetResponse.text();
      stylesheetData = stylesheetData
      .replace(/\[jquery\]/g, 'https://code.jquery.com/jquery-3.6.0.min.js')
      .replace(/\[jquery-tablesorter\]/g, 'https://cdnjs.cloudflare.com/ajax/libs/jquery.tablesorter/2.31.3/js/jquery.tablesorter.min.js')
      .replace(/\[parser-date-iso8601\]/g, 'https://cdnjs.cloudflare.com/ajax/libs/jquery.tablesorter/2.31.3/js/parsers/parser-date-iso8601.min.js')
      .replace(/\[xsl-js\]/g, '')
      .replace(/\[xsl-css\]/g, '/css/sitemap.css')
      .replace(/\[title\]/g, 'Sitemap file')
      .replace(/\[number-of-urls\]/g, 'Number of URLs')
      .replace(/\[sitemap-url\]/g, 'Sitemap URL')
      .replace(/\[url-location\]/g, 'URL location')
      .replace(/\[lastmod\]/g, 'Last Modified')
      .replace(/\[changefreq\]/g, 'Change Frequency')
      .replace(/\[priority\]/g, 'Priority')
      .replace(/\[generated-by\]/g, 'Generated by Simple XML Sitemap Drupal module');

      setCacheHeaders({ req, res });
      res.setHeader('Content-Type', 'text/xsl');
      return res.status(200).send(stylesheetData);
    }

    const sitemapResponse = await fetch(`${BACKEND_URL}/sitemap.xml`);

    if (!sitemapResponse.ok) {
      const sitemapError = await sitemapResponse.text();
      console.error(`sitemap fetch fail: ${sitemapResponse.status}, response: ${sitemapError}`);
      throw new Error(`sitemap fetch fail: ${sitemapResponse.status}`);
    }

    let sitemapData = await sitemapResponse.text();

    sitemapData = sitemapData
    .replace('<?xml-stylesheet type="text/xsl" href="/sitemap_generator/default/sitemap.xsl"?>',
      '<?xml-stylesheet type="text/xsl" href="/api/sitemap?stylesheet=true"?>')
    .replace(/<loc>(https?:\/\/[^<]*)<\/loc>/g, (match, p1) => {
      return match.replace(p1, p1.replace(/^https?:\/\/[^\/]+/, 'https://chineke.org'));
    });

    setCacheHeaders({ req, res });
    res.setHeader('Content-Type', 'application/xml');
    res.status(200).send(sitemapData);
  } catch (error) {
    console.error('error fetch sitemap:', error.message);
    res.status(500).json({ error: 'error fetch sitemap', details: error.message });
  }
}
