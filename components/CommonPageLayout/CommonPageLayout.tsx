// components/CommonPageLayout.js

import { NextSeo } from 'next-seo';
import Layout from '../layout';
import TitleCard from '../TitleCard/TitleCard';
import { useHeaderHeight } from '../../utils/useHeaderHeight';
import styles from './CommonPageLayout.module.scss';

interface CommonPageLayoutProps {
  pageData: any;
  hrefLang: any;
  footerMenu: any;
  headerMenu: any;
  preview: any;
  resourceName: any;
  iframeSrc: any;
}

const CommonPageLayout: React.FC<CommonPageLayoutProps> = ({
  pageData,
  hrefLang,
  footerMenu,
  headerMenu,
  preview,
  resourceName,
  iframeSrc,
}) => {
  const headerHeight = useHeaderHeight();

  return (
    <Layout preview={preview} footerMenu={footerMenu} headerMenu={headerMenu}>
      <NextSeo
        title={pageData?.title}
        description="Generated by create pantheon-decoupled-kit."
        languageAlternates={hrefLang}
      />

      <div style={{ height: headerHeight }}></div>

      <TitleCard
        title={pageData?.title}
        text={
          resourceName === 'node--news' || resourceName === 'node--stories'
            ? null
            : pageData?.body?.value
        }
        backgroundColor={pageData?.field_title_card_bg_color?.color}
        path={pageData.path.alias}
        headerMenu={headerMenu}
      />
      <div className={styles.frameContainer}>
        <div className={styles.frameWrapper}>
          <iframe
            id="etapIframe"
            style={{
              border: 'none',
              width: '100%',
              height: '85vh',
              backgroundColor: 'white',
            }}
            src={iframeSrc}
          ></iframe>
        </div>
      </div>
    </Layout>
  );
};

export default CommonPageLayout;
